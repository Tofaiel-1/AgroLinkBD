/// Single Actionable AI Price Recommendation
class AiPriceRecommendationItem {
  final String title;
  final String commodityOrCategory;
  final PriceCommandAction action;
  final PriceCommandScope scope;
  final String? targetCategory;
  final String? targetDivision;
  final String? targetDistrict;
  final double deltaPercent;
  final double currentAvgPrice;
  final double benchmarkPrice;
  final String urgency; // 'critical', 'high', 'moderate', 'normal'
  final String rationaleBn;
  final String rationaleEn;

  AiPriceRecommendationItem({
    required this.title,
    required this.commodityOrCategory,
    required this.action,
    required this.scope,
    this.targetCategory,
    this.targetDivision,
    this.targetDistrict,
    required this.deltaPercent,
    required this.currentAvgPrice,
    required this.benchmarkPrice,
    required this.urgency,
    required this.rationaleBn,
    required this.rationaleEn,
  });

  Map<String, dynamic> toMap() {
    return {
      'title': title,
      'commodityOrCategory': commodityOrCategory,
      'action': action.name,
      'scope': scope.name,
      'targetCategory': targetCategory,
      'targetDivision': targetDivision,
      'targetDistrict': targetDistrict,
      'deltaPercent': deltaPercent,
      'currentAvgPrice': currentAvgPrice,
      'benchmarkPrice': benchmarkPrice,
      'urgency': urgency,
      'rationaleBn': rationaleBn,
      'rationaleEn': rationaleEn,
    };
  }

  factory AiPriceRecommendationItem.fromMap(Map<String, dynamic> map) {
    return AiPriceRecommendationItem(
      title: map['title'] ?? 'বাজার সমন্বয় সুপারিশ',
      commodityOrCategory: map['commodityOrCategory'] ?? 'সার্বিক বাজার',
      action: PriceCommandAction.values.firstWhere(
        (a) => a.name == map['action'],
        orElse: () => PriceCommandAction.decrease,
      ),
      scope: PriceCommandScope.values.firstWhere(
        (s) => s.name == map['scope'],
        orElse: () => PriceCommandScope.all,
      ),
      targetCategory: map['targetCategory'],
      targetDivision: map['targetDivision'],
      targetDistrict: map['targetDistrict'],
      deltaPercent: (map['deltaPercent'] as num?)?.toDouble() ?? 5.0,
      currentAvgPrice: (map['currentAvgPrice'] as num?)?.toDouble() ?? 0.0,
      benchmarkPrice: (map['benchmarkPrice'] as num?)?.toDouble() ?? 0.0,
      urgency: map['urgency'] ?? 'moderate',
      rationaleBn: map['rationaleBn'] ?? '',
      rationaleEn: map['rationaleEn'] ?? '',
    );
  }
}

/// Comprehensive Market Intelligence Report Generated by AI
class AiMarketAnalysisReport {
  final String id;
  final String overviewBn;
  final String overviewEn;
  final int stabilityScore; // 0 - 100
  final String marketRiskLevel; // 'স্বাভাবিক', 'সতর্কতা', 'উচ্চ ঝুঁকি', 'সংকটপূর্ণ'
  final int totalProductsAnalyzed;
  final int totalFishLotsAnalyzed;
  final int recentOrdersAnalyzed;
  final double totalOrderVolumeBdt;
  final List<AiPriceRecommendationItem> recommendations;
  final DateTime timestamp;
  final String analysisEngine;

  AiMarketAnalysisReport({
    required this.id,
    required this.overviewBn,
    required this.overviewEn,
    required this.stabilityScore,
    required this.marketRiskLevel,
    required this.totalProductsAnalyzed,
    required this.totalFishLotsAnalyzed,
    required this.recentOrdersAnalyzed,
    required this.totalOrderVolumeBdt,
    required this.recommendations,
    required this.timestamp,
    required this.analysisEngine,
  });

  Map<String, dynamic> toMap() {
    return {
      'overviewBn': overviewBn,
      'overviewEn': overviewEn,
      'stabilityScore': stabilityScore,
      'marketRiskLevel': marketRiskLevel,
      'totalProductsAnalyzed': totalProductsAnalyzed,
      'totalFishLotsAnalyzed': totalFishLotsAnalyzed,
      'recentOrdersAnalyzed': recentOrdersAnalyzed,
      'totalOrderVolumeBdt': totalOrderVolumeBdt,
      'recommendations': recommendations.map((r) => r.toMap()).toList(),
      'timestamp': Timestamp.fromDate(timestamp),
      'analysisEngine': analysisEngine,
    };
  }

  factory AiMarketAnalysisReport.fromMap(Map<String, dynamic> map, String id) {
    return AiMarketAnalysisReport(
      id: id,
      overviewBn: map['overviewBn'] ?? '',
      overviewEn: map['overviewEn'] ?? '',
      stabilityScore: (map['stabilityScore'] as num?)?.toInt() ?? 75,
      marketRiskLevel: map['marketRiskLevel'] ?? 'স্বাভাবিক',
      totalProductsAnalyzed: (map['totalProductsAnalyzed'] as num?)?.toInt() ?? 0,
      totalFishLotsAnalyzed: (map['totalFishLotsAnalyzed'] as num?)?.toInt() ?? 0,
      recentOrdersAnalyzed: (map['recentOrdersAnalyzed'] as num?)?.toInt() ?? 0,
      totalOrderVolumeBdt: (map['totalOrderVolumeBdt'] as num?)?.toDouble() ?? 0.0,
      recommendations: (map['recommendations'] as List<dynamic>? ?? [])
          .map((item) => AiPriceRecommendationItem.fromMap(Map<String, dynamic>.from(item)))
          .toList(),
      timestamp: (map['timestamp'] as Timestamp?)?.toDate() ?? DateTime.now(),
      analysisEngine: map['analysisEngine'] ?? 'Gemini AI',
    );
  }
}

/// Masterclass AI Service for Automated Buying & Selling Price Analysis
class AiPriceAnalysisService {
  static final FirebaseFirestore _firestore = FirebaseFirestore.instance;

  static String get _apiKey =>
      dotenv.env['GEMINI_API_KEY'] ?? dotenv.env['API_KEY'] ?? '';

  static final List<String> _modelCandidates = [
    'gemini-2.5-flash',
    'gemini-flash-latest',
    'gemini-2.0-flash',
    'gemini-1.5-flash',
    'gemini-1.5-pro',
  ];

  /// Run complete market analysis on live Buying & Selling data
  static Future<AiMarketAnalysisReport> runMarketAnalysis() async {
    debugPrint('🤖 Starting AI Buying & Selling Market Analysis...');

    // 1. Fetch live agricultural products
    final productsSnap = await _firestore
        .collection('products')
        .where('status', isEqualTo: 'active')
        .limit(100)
        .get()
        .catchError((_) => _firestore.collection('products').limit(100).get());

    // 2. Fetch live fish harvest lots
    final fishLotsSnap = await _firestore
        .collection('fish_marketplace_lots')
        .where('status', isEqualTo: 'active')
        .limit(100)
        .get()
        .catchError((_) => _firestore.collection('fish_marketplace_lots').limit(100).get());

    // 3. Fetch recent trade orders (Buying activity)
    final ordersSnap = await _firestore
        .collection('orders')
        .orderBy('createdAt', descending: true)
        .limit(50)
        .get()
        .catchError((_) => _firestore.collection('orders').limit(50).get());

    // 4. Fetch central benchmark rates
    final marketPricesSnap = await _firestore.collection('market_prices').get();

    // ─── Mathematical Aggregations ───────────────────────────
    final productDocs = productsSnap.docs;
    final fishDocs = fishLotsSnap.docs;
    final orderDocs = ordersSnap.docs;
    final benchmarkDocs = marketPricesSnap.docs;

    // Benchmarks lookup: name/category -> currentPrice
    final Map<String, double> benchmarkMap = {};
    for (final doc in benchmarkDocs) {
      final data = doc.data();
      final name = (data['productName'] ?? data['name'] ?? '').toString().toLowerCase();
      final category = (data['category'] ?? '').toString().toLowerCase();
      final price = (data['currentPrice'] ?? data['price'] ?? 0.0) as num;
      if (name.isNotEmpty) benchmarkMap[name] = price.toDouble();
      if (category.isNotEmpty) benchmarkMap[category] = price.toDouble();
    }

    // Product Category groups: category -> list of prices
    final Map<String, List<double>> cropCatPrices = {};
    for (final doc in productDocs) {
      final data = doc.data();
      final cat = (data['category'] ?? 'অন্যান্য').toString();
      final price = ((data['price'] ?? 0.0) as num).toDouble();
      if (price > 0) {
        cropCatPrices.putIfAbsent(cat, () => []).add(price);
      }
    }

    // Fish species groups
    final Map<String, List<double>> fishSpeciesPrices = {};
    for (final doc in fishDocs) {
      final data = doc.data();
      final species = (data['species'] ?? data['fishType'] ?? 'মাছ').toString();
      final price = ((data['pricePerKg'] ?? 0.0) as num).toDouble();
      if (price > 0) {
        fishSpeciesPrices.putIfAbsent(species, () => []).add(price);
      }
    }

    // Order Volume
    double totalOrderVolume = 0;
    for (final doc in orderDocs) {
      final data = doc.data();
      final amount = (data['totalAmount'] ?? data['amount'] ?? 0.0) as num;
      totalOrderVolume += amount.toDouble();
    }

    // Prepare Statistical Market Summary
    final buffer = StringBuffer();
    buffer.writeln('Market State Summary:');
    buffer.writeln('- Active Crop Listings: ${productDocs.length}');
    buffer.writeln('- Active Fish Lots: ${fishDocs.length}');
    buffer.writeln('- Recent Buyer Orders Evaluated: ${orderDocs.length}');
    buffer.writeln('- Total Trade Volume Evaluated: ৳${totalOrderVolume.toStringAsFixed(0)}');
    buffer.writeln('\nActive Crop Category Averages vs Benchmarks:');
    cropCatPrices.forEach((cat, prices) {
      final avg = prices.reduce((a, b) => a + b) / prices.length;
      final bench = benchmarkMap[cat.toLowerCase()] ?? benchmarkMap['সবজি'] ?? avg;
      final diffPct = bench > 0 ? ((avg - bench) / bench) * 100 : 0.0;
      buffer.writeln('  * $cat: Avg ৳${avg.toStringAsFixed(1)}, Benchmark ৳${bench.toStringAsFixed(1)}, Diff: ${diffPct.toStringAsFixed(1)}%');
    });

    buffer.writeln('\nFish Species Averages vs Benchmarks:');
    fishSpeciesPrices.forEach((species, prices) {
      final avg = prices.reduce((a, b) => a + b) / prices.length;
      final bench = benchmarkMap[species.toLowerCase()] ?? benchmarkMap['মাছ'] ?? avg;
      final diffPct = bench > 0 ? ((avg - bench) / bench) * 100 : 0.0;
      buffer.writeln('  * $species: Avg ৳${avg.toStringAsFixed(1)}, Benchmark ৳${bench.toStringAsFixed(1)}, Diff: ${diffPct.toStringAsFixed(1)}%');
    });

    final marketContext = buffer.toString();

    // ─── Try Gemini API Analysis ─────────────────────────────
    AiMarketAnalysisReport? aiReport;
    if (_apiKey.isNotEmpty) {
      for (final modelName in _modelCandidates) {
        try {
          final model = GenerativeModel(
            model: modelName,
            apiKey: _apiKey,
            systemInstruction: Content.system(_getSystemPrompt()),
            generationConfig: GenerationConfig(
              temperature: 0.2, // High factual consistency
              topK: 30,
              topP: 0.8,
              maxOutputTokens: 1200,
            ),
          );

          final response = await model.generateContent([
            Content.text('Please analyze this market data and output JSON:\n$marketContext'),
          ]);

          final text = response.text?.trim() ?? '';
          if (text.isNotEmpty) {
            aiReport = _parseGeminiResponse(
              text,
              productDocs.length,
              fishDocs.length,
              orderDocs.length,
              totalOrderVolume,
              modelName,
            );
            if (aiReport != null) break;
          }
        } catch (e) {
          debugPrint('⚠️ Gemini API Price Analysis failed on $modelName: $e');
        }
      }
    }

    // ─── Deterministic High-Precision Fallback (if offline or API key exhausted) ──
    aiReport ??= _generateDeterministicReport(
      productDocs.length,
      fishDocs.length,
      orderDocs.length,
      totalOrderVolume,
      cropCatPrices,
      fishSpeciesPrices,
      benchmarkMap,
    );

    // ─── Persist to Firestore for Audit & History ─────────────
    try {
      final docRef = await _firestore.collection('ai_price_recommendations').add(aiReport.toMap());
      // Also write latest trend snapshot
      await _firestore.collection('market_trend_analyses').doc('latest').set({
        'stabilityScore': aiReport.stabilityScore,
        'marketRiskLevel': aiReport.marketRiskLevel,
        'recommendationsCount': aiReport.recommendations.length,
        'updatedAt': FieldValue.serverTimestamp(),
      }, SetOptions(merge: true));

      return AiMarketAnalysisReport(
        id: docRef.id,
        overviewBn: aiReport.overviewBn,
        overviewEn: aiReport.overviewEn,
        stabilityScore: aiReport.stabilityScore,
        marketRiskLevel: aiReport.marketRiskLevel,
        totalProductsAnalyzed: aiReport.totalProductsAnalyzed,
        totalFishLotsAnalyzed: aiReport.totalFishLotsAnalyzed,
        recentOrdersAnalyzed: aiReport.recentOrdersAnalyzed,
        totalOrderVolumeBdt: aiReport.totalOrderVolumeBdt,
        recommendations: aiReport.recommendations,
        timestamp: aiReport.timestamp,
        analysisEngine: aiReport.analysisEngine,
      );
    } catch (e) {
      debugPrint('⚠️ Could not save ai_price_recommendations to Firestore: $e');
      return aiReport;
    }
  }

