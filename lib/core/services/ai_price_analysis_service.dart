  /// Parse JSON from Gemini
  static AiMarketAnalysisReport? _parseGeminiResponse(
    String rawResponse,
    int productsCount,
    int fishLotsCount,
    int ordersCount,
    double totalVolume,
    String modelName,
  ) {
    try {
      String clean = rawResponse.replaceAll('```json', '').replaceAll('```', '').trim();
      final startIndex = clean.indexOf('{');
      final endIndex = clean.lastIndexOf('}');
      if (startIndex != -1 && endIndex != -1 && endIndex > startIndex) {
        clean = clean.substring(startIndex, endIndex + 1);
      }

      final Map<String, dynamic> data = jsonDecode(clean);
      final rawRecs = (data['recommendations'] as List<dynamic>? ?? []);
      final List<AiPriceRecommendationItem> recs = [];

      for (final r in rawRecs) {
        final map = Map<String, dynamic>.from(r);
        recs.add(AiPriceRecommendationItem.fromMap(map));
      }

      return AiMarketAnalysisReport(
        id: '',
        overviewBn: data['overviewBn'] ?? 'বাজারের ক্রয়-বিক্রয় পরিস্থিতি পর্যালোচনা করা হয়েছে।',
        overviewEn: data['overviewEn'] ?? 'Market trading and buying activity evaluated.',
        stabilityScore: (data['stabilityScore'] as num?)?.toInt() ?? 75,
        marketRiskLevel: data['marketRiskLevel'] ?? 'স্বাভাবিক',
        totalProductsAnalyzed: productsCount,
        totalFishLotsAnalyzed: fishLotsCount,
        recentOrdersAnalyzed: ordersCount,
        totalOrderVolumeBdt: totalVolume,
        recommendations: recs,
        timestamp: DateTime.now(),
        analysisEngine: 'Gemini AI ($modelName)',
      );
    } catch (e) {
      debugPrint('⚠️ Error parsing Gemini JSON: $e');
      return null;
    }
  }

  /// Grounded Deterministic Statistical Engine (Zero Hallucination Fallback)
  static AiMarketAnalysisReport _generateDeterministicReport(
    int productsCount,
    int fishLotsCount,
    int ordersCount,
    double totalVolume,
    Map<String, List<double>> cropCatPrices,
    Map<String, List<double>> fishSpeciesPrices,
    Map<String, double> benchmarkMap,
  ) {
    final List<AiPriceRecommendationItem> recommendations = [];
    int anomalyCount = 0;

    // Check crop categories
    cropCatPrices.forEach((category, prices) {
      if (prices.isEmpty) return;
      final avg = prices.reduce((a, b) => a + b) / prices.length;
      final bench = benchmarkMap[category.toLowerCase()] ?? benchmarkMap['সবজি'] ?? avg;
      if (bench <= 0) return;

      final diffPct = ((avg - bench) / bench) * 100;

      // Price Surge > 15% above benchmark -> Decrease recommendation
      if (diffPct > 15.0) {
        anomalyCount++;
        final delta = (diffPct * 0.7).clamp(5.0, 22.0);
        recommendations.add(
          AiPriceRecommendationItem(
            title: '$category ক্যাটাগরিতে অস্বাভাবিক মূল্যবৃদ্ধি নিয়ন্ত্রণ',
            commodityOrCategory: category,
            action: PriceCommandAction.decrease,
            scope: PriceCommandScope.category,
            targetCategory: category,
            deltaPercent: double.parse(delta.toStringAsFixed(1)),
            currentAvgPrice: double.parse(avg.toStringAsFixed(1)),
            benchmarkPrice: double.parse(bench.toStringAsFixed(1)),
            urgency: diffPct > 25 ? 'critical' : 'high',
            rationaleBn: '$category-এর গড় দর (৳${avg.toStringAsFixed(0)}/কেজি) সরকারি বাজার রেটের চেয়ে ${diffPct.toStringAsFixed(0)}% বেশি। ক্রেতা স্বার্থে $delta% দর কমানোর সুপারিশ।',
            rationaleEn: 'Average listing price is ${diffPct.toStringAsFixed(0)}% higher than benchmark. $delta% price reduction advised.',
          ),
        );
      }
      // Market Crash > 15% below benchmark -> Increase / Price Support recommendation
      else if (diffPct < -15.0) {
        anomalyCount++;
        final delta = (diffPct.abs() * 0.6).clamp(5.0, 20.0);
        recommendations.add(
          AiPriceRecommendationItem(
            title: '$category ক্যাটাগরিতে বাজার ধস রোধ ও কৃষক সুরক্ষা',
            commodityOrCategory: category,
            action: PriceCommandAction.increase,
            scope: PriceCommandScope.category,
            targetCategory: category,
            deltaPercent: double.parse(delta.toStringAsFixed(1)),
            currentAvgPrice: double.parse(avg.toStringAsFixed(1)),
            benchmarkPrice: double.parse(bench.toStringAsFixed(1)),
            urgency: diffPct.abs() > 25 ? 'critical' : 'high',
            rationaleBn: '$category-এর বর্তমান দর (৳${avg.toStringAsFixed(0)}/কেজি) বাজার রেটের চেয়ে ${diffPct.abs().toStringAsFixed(0)}% কম। কৃষকের ক্ষতি কমাতে $delta% দর সমন্বয় প্রয়োজন।',
            rationaleEn: 'Average listing price is ${diffPct.abs().toStringAsFixed(0)}% below benchmark. $delta% price support advised.',
          ),
        );
      }
    });

    // Check fish species
    fishSpeciesPrices.forEach((species, prices) {
      if (prices.isEmpty) return;
      final avg = prices.reduce((a, b) => a + b) / prices.length;
      final bench = benchmarkMap[species.toLowerCase()] ?? benchmarkMap['মাছ'] ?? avg;
      if (bench <= 0) return;

      final diffPct = ((avg - bench) / bench) * 100;

      if (diffPct > 15.0) {
        anomalyCount++;
        final delta = (diffPct * 0.65).clamp(5.0, 20.0);
        recommendations.add(
          AiPriceRecommendationItem(
            title: '$species মাছের দর সমন্বয় ও সাধারণ ক্রেতা স্বস্তি',
            commodityOrCategory: species,
            action: PriceCommandAction.decrease,
            scope: PriceCommandScope.fish,
            deltaPercent: double.parse(delta.toStringAsFixed(1)),
            currentAvgPrice: double.parse(avg.toStringAsFixed(1)),
            benchmarkPrice: double.parse(bench.toStringAsFixed(1)),
            urgency: 'high',
            rationaleBn: '$species মাছের পাইকারী দর (৳${avg.toStringAsFixed(0)}/কেজি) গড় হারের চেয়ে ${diffPct.toStringAsFixed(0)}% বেশি। $delta% দর সমন্বয় প্রস্তাবিত।',
            rationaleEn: '$species price is ${diffPct.toStringAsFixed(0)}% above benchmark. $delta% price reduction advised.',
          ),
        );
      } else if (diffPct < -15.0) {
        anomalyCount++;
        final delta = (diffPct.abs() * 0.6).clamp(5.0, 20.0);
        recommendations.add(
          AiPriceRecommendationItem(
            title: '$species চাষীদের উৎপাদন ক্ষতি রক্ষা সহায়তা',
            commodityOrCategory: species,
            action: PriceCommandAction.increase,
            scope: PriceCommandScope.fish,
            deltaPercent: double.parse(delta.toStringAsFixed(1)),
            currentAvgPrice: double.parse(avg.toStringAsFixed(1)),
            benchmarkPrice: double.parse(bench.toStringAsFixed(1)),
            urgency: 'high',
            rationaleBn: '$species মাছের দর অত্যধিক কমে যাওয়ায় খামারিরা ক্ষতিগ্রস্ত হচ্ছেন। $delta% দর সহায়তা প্রস্তাবিত।',
            rationaleEn: '$species price crashed by ${diffPct.abs().toStringAsFixed(0)}%. $delta% price support recommended.',
          ),
        );
      }
    });

    // If balanced, provide a stabilization recommendation
    if (recommendations.isEmpty) {
      recommendations.add(
        AiPriceRecommendationItem(
          title: 'বাজার স্থিতিশীল রয়েছে: বেঞ্চমার্ক সিঙ্ক সুপারিশ',
          commodityOrCategory: 'সামগ্রিক বাজার',
          action: PriceCommandAction.syncBenchmark,
          scope: PriceCommandScope.all,
          deltaPercent: 0.0,
          currentAvgPrice: 0.0,
          benchmarkPrice: 0.0,
          urgency: 'normal',
          rationaleBn: 'কৃষি ফসল ও মাছের গড় দর বর্তমানে সরকারি বেঞ্চমার্কের সাথে সামঞ্জস্যপূর্ণ রয়েছে। নতুন কোনো কৃত্রিম হস্তক্ষেপ প্রয়োজন নেই।',
          rationaleEn: 'Market prices currently align closely with benchmark rates. Zero intervention needed.',
        ),
      );
    }

    final int stabilityScore = (100 - (anomalyCount * 14)).clamp(35, 96);
    final String riskLevel = stabilityScore < 50
        ? 'উচ্চ ঝুঁকি'
        : stabilityScore < 75
            ? 'সতর্কতা'
            : 'স্বাভাবিক';

    return AiMarketAnalysisReport(
      id: '',
      overviewBn: 'মোট $productsCount টি ফসল, $fishLotsCount টি মাছের লট এবং $ordersCount টি সাম্প্রতিক ক্রয়-বিক্রয় অর্ডার বিশ্লেষণ করা হয়েছে। বাজারে $anomalyCount টি পণ্যে অস্বাভাবিক দর তারতম্য শনাক্ত হয়েছে।',
      overviewEn: 'Analyzed $productsCount crop listings, $fishLotsCount fish lots, and $ordersCount recent trade orders. Detected $anomalyCount pricing anomalies across the marketplace.',
      stabilityScore: stabilityScore,
      marketRiskLevel: riskLevel,
      totalProductsAnalyzed: productsCount,
      totalFishLotsAnalyzed: fishLotsCount,
      recentOrdersAnalyzed: ordersCount,
      totalOrderVolumeBdt: totalVolume,
      recommendations: recommendations,
      timestamp: DateTime.now(),
      analysisEngine: 'Grounded Real-Time Market Engine',
    );
  }

  /// Stream historical AI recommendations
  static Stream<List<AiMarketAnalysisReport>> streamHistoricalReports({int limit = 20}) {
    return _firestore
        .collection('ai_price_recommendations')
        .orderBy('timestamp', descending: true)
        .limit(limit)
        .snapshots()
        .map((snap) {
      return snap.docs.map((doc) => AiMarketAnalysisReport.fromMap(doc.data(), doc.id)).toList();
    });
  }
